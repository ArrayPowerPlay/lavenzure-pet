"""Write ``src/_version.py`` (git-ignored) from the git tag, just before packaging.

Usage: ``python scripts/write_version.py`` (version from ``git describe``), or pass the version
explicitly, e.g. ``python scripts/write_version.py 0.1.0`` (the release workflow does this with the
tag it was started for). Prints the version it wrote.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

import version  # noqa: E402


def main(argv: list[str]) -> int:
    """Write the version file; returns the process exit code."""
    chosen = argv[1].lstrip("v") if len(argv) > 1 else version.git_version()
    if not chosen:
        print("No v* git tag found (and no version given); cannot write the version.",
              file=sys.stderr)
        return 1
    target = ROOT / "src" / "_version.py"
    target.write_text(
        '"""Generated by scripts/write_version.py at build time. Not in git."""\n'
        f'VERSION = "{chosen}"\n',
        encoding="utf-8",
    )
    print(chosen)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
